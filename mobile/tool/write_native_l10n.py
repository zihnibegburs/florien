def loc_unit(value: str) -> dict:
    return {"stringUnit": {"state": "translated", "value": value}}


def write_infoplist() -> None:
    runner = ROOT / "ios" / "Runner"
    for lang, folder in IOS_LPROJ.items():
        path = runner / f"{folder}.lproj" / "InfoPlist.strings"
        path.parent.mkdir(parents=True, exist_ok=True)
        lines = []
        for key, translations in INFO_PLIST.items():
            value = translations[lang].replace('"', '\\"')
            lines.append(f'"{key}" = "{value}";')
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")


def write_android() -> None:
    res = ROOT / "android" / "app" / "src" / "main" / "res"
    for lang, folder in ANDROID_VALUES.items():
        path = res / folder / "strings.xml"
        path.parent.mkdir(parents=True, exist_ok=True)
        parts = [
            '<?xml version="1.0" encoding="utf-8"?>',
            "<resources>",
        ]
        quote_map = {'"': "&quot;", "'": "&apos;"}
        for key, translations in ANDROID.items():
            parts.append(
                f'    <string name="{key}">{xml.escape(translations[lang], quote_map)}</string>'
            )
        parts.append("</resources>")
        parts.append("")
        path.write_text("\n".join(parts), encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")


def expand_xcstrings() -> None:
    path = ROOT / "ios" / "Runner" / "Localizable.xcstrings"
    data = json.loads(path.read_text(encoding="utf-8"))
    strings = data.setdefault("strings", {})
    xc_lang = {
        "en": "en",
        "es": "es",
        "de": "de",
        "fr": "fr",
        "pt": "pt",
        "ja": "ja",
        "ko": "ko",
        "zh": "zh-Hans",
        "ar": "ar",
        "tr": "tr",
    }
    for key, extras in INTENT_EXTRA_LANGS.items():
        entry = strings.setdefault(key, {"extractionState": "manual", "localizations": {}})
        locs = entry.setdefault("localizations", {})
        for lang, value in extras.items():
            locs[xc_lang[lang]] = loc_unit(value)
    for key, translations in XCSTRING_EXTRA.items():
        locs = {xc_lang[lang]: loc_unit(value) for lang, value in translations.items()}
        strings[key] = {"extractionState": "manual", "localizations": locs}
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


